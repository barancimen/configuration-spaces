"""Write examples/ratchet_drive.yaml: a ratchet drive with a gear train, a slider and a detent.

    python3 examples/make_ratchet_drive.py > examples/ratchet_drive.yaml

The mechanism (metres; all motion in planes parallel to xy):
  lever       oscillates about the ratchet axle, driven by a motor
  drivePawl   on the lever, spring-loaded: pushes a ratchet tooth on each forward stroke and
              slides back over the teeth on the return stroke
  ratchet     12 sawtooth teeth around a hub, plus gear A (24 teeth) on the same body
  holdPawl    on the frame, spring-loaded: stops the ratchet from turning back (the latch)
  gearB       idler (12 teeth), gearC output (20 teeth): exact gear couplings
  rod, slider a crank pin on gearC drives a connecting rod and a slider on a rail (a closed loop)
  catch       spring-loaded detent that clicks into a V-notch on the slider
  frame       base plate
Pawls lie along the tangent of the tooth circle at their contact point, so a blocked tooth pushes
straight along the pawl toward its pivot. Contacts and springs are simulation-only (MuJoCo).
"""
import math

R_ROOT, R_TIP, HUB = 0.072, 0.100, 0.075     # tooth root (inside the hub), tooth tip, hub radius
TEETH, T = 12, 0.010                          # tooth count, half thickness of the ratchet layer


def pts(points, z0, dz):
    """A prism: 2D outline points extruded from z0 - dz to z0 + dz, as a hull list."""
    return "[" + ", ".join(f"[{x:.4f}, {y:.4f}, {z:.4f}]" for x, y in points for z in (z0 - dz, z0 + dz)) + "]"


def tooth(k):
    """Sawtooth: radial (steep) face at angle a, slope from the tip at a down to the root at a + 30 deg.
    A pawl resting in the teeth lets the wheel turn counterclockwise and blocks clockwise."""
    a = 2 * math.pi * k / TEETH
    b = a + 2 * math.pi / TEETH
    return [(R_ROOT * math.cos(a), R_ROOT * math.sin(a)), (R_TIP * math.cos(a), R_TIP * math.sin(a)),
            (R_ROOT * math.cos(b), R_ROOT * math.sin(b))]


def main():
    out = []
    w = out.append
    body = __doc__.split("\n\n", 2)[2].strip()          # the mechanism description, without the usage lines
    w("# Ratchet drive: generated by examples/make_ratchet_drive.py (edit that, then rerun it).\n# "
      + body.replace("\n", "\n# "))
    w("""name: ratchet_drive
bodies:
  world:
    frames:
      axle: {}                                      # ratchet and lever turn about this axis
      holdPivot: {at: [0.08, 0.1, 0]}
      axleB: {at: [0.09, 0, 0]}
      axleC: {at: [0.17, 0, 0]}
      rail: {at: [0.17, 0, -0.045], z: [1, 0, 0]}   # the slider moves along x
      catchPivot: {at: [0.36, 0.03, -0.045]}
  frame:
    color: "#3b4652"
    shape: {box: [0.52, 0.3, 0.005], at: [0.16, 0.03, -0.06]}
  ratchet:
    color: "#b8862b"
    shape:
      union:
        - {cylinder: [0.075, 0.02]}                    # hub
        - {cylinder: [0.06, 0.01], at: [0, 0, -0.03]}  # gear A, 24 teeth (coupling, no tooth contact)""")
    for k in range(TEETH):
        w(f"        - hull: {pts(tooth(k), 0, T)}")
    # lever: a slanted bar from the axle to the drive pawl's pivot at (-0.1, 0.08), above the ratchet
    px, py = -0.1, 0.08
    L = math.hypot(px, py)
    ux, uy = px / L, py / L
    nx, ny = -uy, ux
    hw, ext = 0.010, 0.015
    lever = [(-ext * ux + hw * nx, -ext * uy + hw * ny), (-ext * ux - hw * nx, -ext * uy - hw * ny),
             (px + ext * ux - hw * nx, py + ext * uy - hw * ny), (px + ext * ux + hw * nx, py + ext * uy + hw * ny)]
    w(f"""  lever:
    color: "#3f6f9f"
    shape: {{hull: {pts(lever, 0.025, 0.004)}}}
    frames: {{pawlPivot: {{at: [{px}, {py}, 0]}}}}
  drivePawl:                                       # along the tangent at (-0.1, 0); hook reaches into the teeth
    color: "#8a96a3"
    shape:
      union:
        - hull: {pts([(-0.012, 0.004), (0.0, 0.004), (0.0, -0.075), (-0.012, -0.075)], 0, 0.008)}
        - hull: {pts([(-0.006, -0.066), (0.0, -0.066), (0.013, -0.082), (-0.004, -0.084)], 0, 0.008)}
  holdPawl:                                        # along the tangent at (0, 0.1)
    color: "#8a96a3"
    shape:
      union:
        - hull: {pts([(0.004, 0.0), (0.004, 0.012), (-0.075, 0.012), (-0.075, 0.0)], 0, 0.008)}
        - hull: {pts([(-0.066, 0.006), (-0.066, 0.0), (-0.082, -0.013), (-0.084, 0.004)], 0, 0.008)}
  gearB:
    color: "#a3592e"
    shape:
      union:
        - {{cylinder: [0.03, 0.01], at: [0, 0, -0.03]}}
        - {{box: [0.05, 0.006, 0.012], at: [0, 0, -0.03]}}     # spoke, to see it turn
  gearC:
    color: "#3f8a78"
    shape:
      union:
        - {{cylinder: [0.05, 0.01], at: [0, 0, -0.03]}}
        - {{box: [0.09, 0.008, 0.012], at: [0, 0, -0.03]}}
    frames: {{pin: {{at: [0.035, 0, -0.045]}}}}
  rod:
    color: "#6c5c9e"
    shape: {{box: [0.15, 0.008, 0.004], at: [0.075, 0, 0]}}
    frames: {{a: {{}}, b: {{at: [0.15, 0, 0]}}}}
  slider:                                          # a block with a V-notch on top
    color: "#5b7f2e"
    shape:
      union:
        - {{box: [0.06, 0.02, 0.01]}}
        - hull: {pts([(-0.03, 0.01), (-0.001, 0.01), (-0.007, 0.018), (-0.03, 0.018)], 0, 0.005)}
        - hull: {pts([(0.001, 0.01), (0.03, 0.01), (0.03, 0.018), (0.007, 0.018)], 0, 0.005)}
    frames: {{rail: {{z: [1, 0, 0]}}, pin: {{}}}}
  catch:                                           # detent arm with a V tip
    color: "#8d3d4a"
    shape:
      union:
        - hull: {pts([(0.003, 0.0), (0.003, 0.008), (-0.04, 0.008), (-0.04, 0.0)], 0, 0.004)}
        - hull: {pts([(-0.046, 0.001), (-0.034, 0.001), (-0.04, -0.012)], 0, 0.004)}
constraints:
  - fixed: [world, frame]
  - revolute: [world.axle, ratchet]
    name: ratchet
  - revolute: [world.axle, lever]
    name: lever
    range: [-0.6, 0.6]
  - revolute: [lever.pawlPivot, drivePawl]
    name: drivePawl
    spring: {{stiffness: 0.02, rest: 0.35, damping: 0.001}}     # positive angle pushes into the teeth
  - revolute: [world.holdPivot, holdPawl]
    name: holdPawl
    spring: {{stiffness: 0.02, rest: 0.35, damping: 0.001}}
  - revolute: [world.axleB, gearB]
    name: gearB
  - revolute: [world.axleC, gearC]
    name: gearC
  - gear: [ratchet, gearB]
    teeth: [24, 12]
  - gear: [gearB, gearC]
    teeth: [12, 20]
  - revolute: [gearC.pin, rod.a]
    name: crankPin
  - prismatic: [world.rail, slider.rail]
    name: slide
    range: [0.08, 0.22]
  - revolute: [rod.b, slider.pin]                  # closes the slider-crank loop
    name: wristPin
  - revolute: [world.catchPivot, catch]
    name: catch
    spring: {{stiffness: 0.005, rest: 0.3, damping: 0.0001}}
  # simulation only: these bodies push on each other in MuJoCo
  - contact: [drivePawl, ratchet]
    friction: 0.2
  - contact: [holdPawl, ratchet]
    friction: 0.2
  - contact: [catch, slider]
    friction: 0.2

start:                     # pawls and catch lifted clear; the springs drop them in
  lever: 0
  ratchet: 0
  drivePawl: -0.25
  holdPawl: -0.25
  catch: -0.25

simulation:
  gravity: false           # the mechanism lies flat
  timestep: 0.0005
  motors:
    lever: {{kp: 5, damping: 0.05}}
#   python3 -m cspace.mjcf examples/ratchet_drive.yaml -o ratchet.xml
#   python3 examples/simulate_mujoco.py ratchet.xml --wiggle --amplitude 0.35 --frequency 0.5 --view""")
    print("\n".join(out))


if __name__ == "__main__":
    main()
