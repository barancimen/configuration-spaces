"""Write a System as a Wolfram Language association (.wl) or JSON, plus a text summary."""
import json

from sympy import And, mathematica_code, sstr


def wl(e):
    return mathematica_code(e)


def _list(items):
    return "{" + ", ".join(items) + "}"


def _assoc(pairs, indent="  "):
    if not pairs:
        return "<||>"
    inner = (",\n" + indent + "  ").join(f'"{k}" -> {v}' for k, v in pairs)
    return "<|\n" + indent + "  " + inner + "\n" + indent + "|>"


def _matrix(M):
    return _list(_list(wl(M[i, j]) for j in range(M.cols)) for i in range(M.rows))


def to_wl(system):
    s = system
    head = [f"(* Configuration space of {s.name!r}, generated by cspace. *)",
            f"(* Coordinates: {s.coords}{', trigonometric angles' if s.trig else ''}. *)"]
    head += [f"(* {n.replace('*)', '* )')} *)" for n in s.notes]
    body = [
        ("Name", f'"{s.name}"'),
        ("Parameters", _list(wl(p) for p in s.params)),
        ("Assumptions", wl(And(*s.assumptions)) if s.assumptions else "True"),
        ("Variables", _list(wl(v) for v in s.variables)),
        ("Equations", _list(f"{wl(e)} == 0" for e in s.equations)),
        ("Inequalities", _list(f"{wl(g)} >= 0" for g in s.inequalities)),
        ("Constraints", wl(s.constraints())),
        ("Formula", wl(s.formula())),
        ("Poses", _assoc([(b, _matrix(M)) for b, M in s.poses.items()], "  ")),
        ("Coordinates", _assoc([(j.name, _assoc([(k, wl(e)) for k, e in j.values.items()], "    "))
                                for j in s.joints], "  ")),
        ("Shapes", _assoc([(b, f"Function[{{x, y, z}}, {wl(f)}]") for b, f in s.shapes.items()], "  ")),
    ]
    return "\n".join(head) + "\n\ncspace = " + _assoc(body, "") + ";\n"


def to_json(system):
    s = system
    data = {
        "name": s.name,
        "coords": s.coords,
        "trig": s.trig,
        "parameters": [sstr(p) for p in s.params],
        "assumptions": [sstr(a) for a in s.assumptions],
        "variables": [sstr(v) for v in s.variables],
        "equations": [sstr(e) for e in s.equations],
        "inequalities": [sstr(g) for g in s.inequalities],
        "formulas": [sstr(f) for f in s.formulas],
        "poses": {b: [[sstr(M[i, j]) for j in range(4)] for i in range(4)] for b, M in s.poses.items()},
        "coordinates": {j.name: {k: sstr(e) for k, e in j.values.items()} for j in s.joints},
        "shapes": {b: sstr(f) for b, f in s.shapes.items()},
        "notes": s.notes,
    }
    return json.dumps(data, indent=1) + "\n"


def summary(system):
    s = system
    lines = [f"{s.name}: {len(s.variables)} variables, {len(s.equations)} equations, "
             f"{len(s.inequalities)} inequalities, {len(s.formulas)} other conditions "
             f"({s.coords} coordinates{', trig' if s.trig else ''})",
             f"naive freedom count (6 per body minus each constraint's codimension): {s.naive_dof}"]
    lines += ["  " + n for n in s.notes]
    return "\n".join(lines)
